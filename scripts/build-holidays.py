"""Writes js/my-holidays.js: Malaysia's public holidays, federal and state.

The dates come from the python-holidays package (Malay names). Islamic
holidays follow its calendar and are marked "anggaran" where it estimates
them; the gazette decides. Run once a year, and after a holiday is declared:

    python3 -m pip install holidays
    python3 scripts/build-holidays.py 2026 2027
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import holidays

# python-holidays' state codes, named as malaysia-data.js names them.
STATES = {
    '01': 'Johor', '02': 'Kedah', '03': 'Kelantan', '04': 'Melaka', '05': 'Negeri Sembilan',
    '06': 'Pahang', '07': 'Pulau Pinang', '08': 'Perak', '09': 'Perlis', '10': 'Selangor',
    '11': 'Terengganu', '12': 'Sabah', '13': 'Sarawak', '14': 'W.P. Kuala Lumpur',
    '15': 'W.P. Labuan', '16': 'W.P. Putrajaya',
}

years = [int(y) for y in sys.argv[1:]] or [2026, 2027]
where = defaultdict(set)  # (date, name) -> states
for code, state in STATES.items():
    calendar = holidays.country_holidays('MY', subdiv=code, years=years, language='ms_MY')
    for day in calendar:
        for name in calendar.get_list(day):
            where[(day.isoformat(), name)].add(state)

rows = []
for (day, name), states in sorted(where.items()):
    # Every state: null, so the file stays small and the meaning plain.
    rows.append([day, name, None if len(states) == len(STATES) else sorted(states)])

body = ',\n'.join('  ' + json.dumps(row, ensure_ascii=False) for row in rows)
out = Path(__file__).resolve().parent.parent / 'js' / 'my-holidays.js'
out.write_text(
    f"// Malaysia's public holidays {years[0]}–{years[-1]}: [date, name, states or null for\n"
    f"// every state]. Generated by scripts/build-holidays.py from python-holidays\n"
    f"// {holidays.__version__}; Islamic dates are its reckoning until the gazette.\n"
    f"export const MY_HOLIDAYS = [\n{body},\n];\n",
    encoding='utf-8',
)
print(f'{out.name}: {len(rows)} entries')
