// Builds vendor/cities.js, the searchable city list, from the city-timezones
// package (MIT; Natural Earth populated places). Run: node scripts/build-cities.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const source = JSON.parse(readFileSync(require.resolve('city-timezones/data/cityMap.json'), 'utf8'));

// Malay names people search for that the source lacks or spells in English.
const MALAY_NAMES = [
  ['Mekah', 'Saudi Arabia', 'Asia/Riyadh', 21.42, 39.83],
  ['Madinah', 'Saudi Arabia', 'Asia/Riyadh', 24.47, 39.61],
  ['Kaherah', 'Egypt', 'Africa/Cairo', 30.04, 31.24],
  ['Pulau Pinang', 'Malaysia', 'Asia/Kuala_Lumpur', 5.41, 100.33],
  ['Melaka', 'Malaysia', 'Asia/Kuala_Lumpur', 2.19, 102.25],
  ['Kota Bharu', 'Malaysia', 'Asia/Kuala_Lumpur', 6.13, 102.24],
  ['Labuan', 'Malaysia', 'Asia/Kuching', 5.28, 115.24],
];

function isValidZone(zone) {
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: zone });
    return true;
  } catch (err) {
    if (err instanceof RangeError) return false;
    throw err;
  }
}

const round = (n) => Math.round(n * 100) / 100;
const seen = new Set();
const cities = [];
// Most populous first, so a bare name like "George Town" resolves to the biggest one.
for (const c of [...source].sort((a, b) => b.pop - a.pop)) {
  if (!c.timezone || !isValidZone(c.timezone)) continue;
  const row = [c.city, c.country, c.timezone, round(c.lat), round(c.lng)];
  const key = `${row[0]}|${row[1]}|${row[2]}`;
  if (seen.has(key)) continue;
  seen.add(key);
  cities.push(row);
}

const rows = [...MALAY_NAMES, ...cities];
const body = rows.map((r) => JSON.stringify(r)).join(',\n');
writeFileSync(
  new URL('../vendor/cities.js', import.meta.url),
  `// Generated by scripts/build-cities.mjs from city-timezones (MIT, Natural Earth data). Do not edit by hand.\n` +
  `// [name, country, IANA zone, latitude, longitude], most populous first.\n` +
  `window.WORLD_CITIES = [\n${body}\n];\n`,
);
console.log(`vendor/cities.js: ${rows.length} cities (${source.length - cities.length} source rows skipped)`);
